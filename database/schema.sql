CREATE TABLE IF NOT EXISTS ci_imports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 source_type VARCHAR(16) NOT NULL,
 source_name TEXT NOT NULL,
 headers_json MEDIUMTEXT NOT NULL,
 mapping_json TEXT NOT NULL,
 row_count INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ci_leads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 import_id BIGINT UNSIGNED NOT NULL,
 source_row INT UNSIGNED NOT NULL,
 raw_json MEDIUMTEXT NOT NULL,
 company TEXT NOT NULL,
 address TEXT NOT NULL,
 phones TEXT NOT NULL,
 email TEXT NOT NULL,
 website TEXT NOT NULL,
 INDEX idx_import (import_id, id),
 CONSTRAINT ci_leads_import_fk FOREIGN KEY (import_id) REFERENCES ci_imports(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ci_templates (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL,
 signature CHAR(64) NOT NULL,
 headers_json MEDIUMTEXT NOT NULL,
 mapping_json TEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_signature (signature)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ci_notes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 lead_id BIGINT UNSIGNED NOT NULL,
 phone VARCHAR(100) NOT NULL,
 contact_date DATE NULL,
 comment TEXT NOT NULL,
 followup_date DATE NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_lead (lead_id,id),
 CONSTRAINT ci_notes_lead_fk FOREIGN KEY (lead_id) REFERENCES ci_leads(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ci_feeds (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 import_id BIGINT UNSIGNED NOT NULL UNIQUE,
 token_hash CHAR(64) NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ci_feeds_import_fk FOREIGN KEY (import_id) REFERENCES ci_imports(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ci_login_attempts (
 ip_hash CHAR(64) PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_started BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
